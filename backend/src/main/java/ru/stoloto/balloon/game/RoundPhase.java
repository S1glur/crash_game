package ru.stoloto.balloon.game;

/**
 * Фаза общего раунда. Цикл крутится сервером непрерывно, независимо от того,
 * есть ли вообще игроки: BETTING -> FLYING -> RESULT -> BETTING ...
 */
public enum RoundPhase {

    /** Принимаем ставки. Шар на земле, коэффициент равен 1. */
    BETTING,

    /** Шар летит, коэффициент растёт, можно забирать. */
    FLYING,

    /** Шар лопнул, показываем итог. Ставки уже уходят в следующий раунд. */
    RESULT
}
